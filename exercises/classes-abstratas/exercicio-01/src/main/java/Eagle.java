
/**
 * A classe Eagle estende a classe abstrata Animal e define uma representação do animal águia.
 */
public class Eagle extends Animal{

    /**
     * O método respirar, herdado da classe abstrata Animal, exibe na tela uma mensagem indicando a ação de respirar da águia.
     */
    public void respirar(){
        System.out.println("O eagle respirou!");
    }

     /**
     * O método dormir, herdado da classe abstrata Animal, exibe na tela uma mensagem indicando a ação de dormir da águia.
     */
    public void dormir(){
        System.out.println("O eagle dormiu!");
    }

    /**
     * O método comer, herdado da classe abstrata Animal, exibe na tela uma mensagem indicando a ação de comer da águia.
     */
    public void comer(){
        System.out.println("O eagle comeu!");
    }

    /**
     * O método andar, herdado da classe abstrata Animal, exibe na tela uma mensagem indicando a ação de andar da águia.
     */
    public void andar(){
        System.out.println("O eagle andou!");
    }

    /**
     * O método voar exibe na tela uma mensagem indicando a ação de voar da águia.
     */
    public void voar(){
        System.out.println("O eagle vuou!");
    }
    
}
