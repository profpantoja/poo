
/**
 * A classe abstrata Animal define um padrão de ações para um animal que a estenda.
 * 
 */
public abstract class Animal {

    /**
     * O método abstrato respirar define a ação de respirar para um animal.
     */
    public abstract void respirar(); 

    /**
     * O método abstrato dormir define a ação de dormir para um animal.
     */
    public abstract void dormir();

    /**
     * O método abstrato comer define a ação de comer para um animal.
     */
    public abstract void comer();

    /**
     * O método abstrato andar define a ação de andar para um animal.
     */
    public abstract void andar();
    
}
